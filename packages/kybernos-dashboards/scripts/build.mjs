#!/usr/bin/env node
// scripts/build.mjs: produces `client.js` (never edit it by hand).
//
// The browser half is one file DSH loads as a module. It is assembled from:
//   model.mjs, chart-core.mjs   the pure core, pasted in with their `export`s removed, so the very code the Node tests
//                               run is the code the page runs
//   src/plugin.js               the stylesheet, the source reader, the SVG painters, the widgets, the page / pane / player,
//                               and the registration (CI syntax-checks every .js except `*/src/plugin.js`, which has a
//                               top-level `return`, so the browser body is ONE file with that name)
//
//   node scripts/build.mjs          writes client.js
//   node scripts/build.mjs --check  fails when client.js is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (f) => readFileSync(join(root, f), 'utf8')
const indent = (text, prefix) => text.split('\n').map((l) => (l === '' ? l : prefix + l)).join('\n')

/** A pure module as an expression: its exports become the returned object. */
export function inline (src, name) {
  const names = []
  if (/^import /m.test(src)) throw new Error(`${name}: a pasted module cannot import`)
  let code = src.replace(/^export (async function|function|const|let|class) ([A-Za-z0-9_$]+)/gm, (m, kind, id) => { names.push(id); return `${kind} ${id}` })
  code = code.replace(/^export \{([^}]*)\}[ \t]*$/gm, (m, list) => {
    for (const n of list.split(',').map((s) => s.trim()).filter(Boolean)) if (!names.includes(n)) names.push(n)
    return ''
  })
  if (/^export /m.test(code)) throw new Error(`${name}: an export form the build does not handle`)
  return `const ${name} = (() => {\n${code.trimEnd()}\nreturn { ${names.join(', ')} }\n})()`
}

const SOURCES = ['src/plugin.js']

export function assemble () {
  const core = [inline(read('model.mjs'), 'model'), inline(read('chart-core.mjs'), 'chart')].join('\n')
  const body = SOURCES.map((f) => '// ── ' + f + '\n' + read(f).trimEnd()).join('\n\n')
  return `// @local/kybernos-dashboards: browser bundle GENERATED by scripts/build.mjs (do not edit).
window.__ModuleLoader__.load({
  id: '@local/kybernos-dashboards/client',
  factory (require) {
    try {
${indent(core, '      ')}
      return (function (model, chart) {
${indent(body, '        ')}
      })(model, chart)
    } catch (error) {
      // An exception here would break the whole entry: degrade, this plugin off.
      console.error('[kybernos-dashboards] cannot evaluate, plugin disabled', error)
      return { name: 'kybernos-dashboards/client', inject: [], apply () {} }
    }
  }
})
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = assemble()
  if (process.argv.includes('--check')) {
    const cur = (() => { try { return read('client.js') } catch { return '' } })()
    if (cur !== out) { console.error('client.js is out of date: run node scripts/build.mjs'); process.exit(1) }
    console.log('client.js is up to date')
  } else {
    writeFileSync(join(root, 'client.js'), out)
    console.log(`client.js assembled: ${out.split('\n').length} lines, ${Math.round(out.length / 1024)} KB`)
  }
}
