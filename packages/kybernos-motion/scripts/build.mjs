#!/usr/bin/env node
// scripts/build.mjs: produces `client.js` (never edit it by hand).
//
// The browser half is one file DSH loads as a module. It is assembled from:
//   vendor/mediabunny.iife.js   the MP4/WebM writer (MPL-2.0, see vendor/NOTICES.md)
//   engine.mjs, audio.mjs, render2d.mjs, render-ext.mjs   the pure core, pasted in with their `export`s removed, so the
//                               very code the Node tests run is the code the browser runs (the 3D and Lottie libraries
//                               are NOT in here: the host serves them on demand, see vendor/NOTICES.md)
//   src/plugin.js               the panel and the player
// The same four modules, as text, are also embedded (`RUNTIME_SRC`) so an exported standalone page can carry them.
//
//   node scripts/build.mjs          writes client.js
//   node scripts/build.mjs --check  fails when client.js is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (f) => readFileSync(join(root, f), 'utf8')
const indent = (text, prefix) => text.split('\n').map((l) => (l === '' ? l : prefix + l)).join('\n')

/** A pure module as an expression: its exports become the returned object. */
export function inline (src, name) {
  const names = []
  if (/^import /m.test(src)) throw new Error(`${name}: a pasted module cannot import`)
  let code = src.replace(/^export (async function|function|const|let|class) ([A-Za-z0-9_$]+)/gm, (m, kind, id) => { names.push(id); return `${kind} ${id}` })
  code = code.replace(/^export \{([^}]*)\}[ \t]*$/gm, (m, list) => {
    for (const n of list.split(',').map((s) => s.trim()).filter(Boolean)) if (!names.includes(n)) names.push(n)
    return ''
  })
  if (/^export /m.test(code)) throw new Error(`${name}: an export form the build does not handle`)
  return `const ${name} = (() => {\n${code.trimEnd()}\nreturn { ${names.join(', ')} }\n})()`
}

export function assemble () {
  const vendor = read('vendor/mediabunny.iife.js').trimEnd()
  const modules = [['engine', 'engine.mjs'], ['audio', 'audio.mjs'], ['render2d', 'render2d.mjs'], ['renderExt', 'render-ext.mjs']].map(([n, f]) => inline(read(f), n))
  const runtime = modules.join('\n')
  const body = read('src/plugin.js')
  return `// @local/kybernos-motion: browser bundle GENERATED by scripts/build.mjs (do not edit).
// Mediabunny 1.61.3 (MPL-2.0) is vendored: see vendor/NOTICES.md.
window.__ModuleLoader__.load({
  id: '@local/kybernos-motion/client',
  factory (require) {
    try {
${indent(vendor, '      ')}
${indent(runtime, '      ')}
      const RUNTIME_SRC = ${JSON.stringify(runtime)}
      return (function (engine, audio, render2d, renderExt, Mediabunny, RUNTIME_SRC) {
${indent(body, '        ')}
      })(engine, audio, render2d, renderExt, Mediabunny, RUNTIME_SRC)
    } catch (error) {
      // An exception here would break the whole entry: degrade, this plugin off.
      console.error('[kybernos-motion] cannot evaluate, plugin disabled', error)
      return { name: 'kybernos-motion/client', inject: [], apply () {} }
    }
  }
})
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = assemble()
  if (process.argv.includes('--check')) {
    const cur = (() => { try { return read('client.js') } catch { return '' } })()
    if (cur !== out) { console.error('client.js is out of date: run node scripts/build.mjs'); process.exit(1) }
    console.log('client.js is up to date')
  } else {
    writeFileSync(join(root, 'client.js'), out)
    console.log(`client.js assembled: ${out.split('\n').length} lines, ${Math.round(out.length / 1024)} KB`)
  }
}
