// scripts/build.mjs — produces `client/client.js`.
//
//   1. bundles `mermaid` (npm ESM) as a self-contained IIFE, with no external dependency
//      → vendor/mermaid.iife.js (reproducible, vendored to stay offline)
//   2. concatenates the DSH module-loader header + the bundle + the plugin factory
//      (src/plugin.js)
//
// Usage: node scripts/build.mjs
import { createRequire } from 'node:module'
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require_ = createRequire(import.meta.url)

// Mermaid and esbuild are not dependencies of this package (it stays installable
// offline): they are resolved from the known places of the machine.
const CANDIDATE_DIRS = [
  process.env.DSH_MERMAID_DEPS,
  root,
  join(process.env.HOME ?? '', '.dsh/profiles/web')
].filter(Boolean)

function resolveOrNull(id) {
  for (const dir of CANDIDATE_DIRS) {
    try {
      return require_.resolve(id, { paths: [dir] })
    } catch {
      /* next candidate */
    }
  }
  return null
}

const mermaidPkgPath = resolveOrNull('mermaid/package.json')
const esbuildPath = resolveOrNull('esbuild')
const vendorPath = join(root, 'vendor', 'mermaid.iife.js')

let mermaidBundle
let mermaidVersion
if (mermaidPkgPath && esbuildPath) {
  mermaidVersion = JSON.parse(readFileSync(mermaidPkgPath, 'utf8')).version
  const resolveDir = dirname(mermaidPkgPath)
  const esbuild = require_(esbuildPath)

  mkdirSync(join(root, 'vendor'), { recursive: true })

  const result = await esbuild.build({
    stdin: {
      contents: "import mermaid from 'mermaid'\nexport default mermaid\n",
      resolveDir,
      sourcefile: 'dsh-mermaid-entry.mjs',
      loader: 'js'
    },
    bundle: true,
    format: 'iife',
    globalName: '__DSH_MERMAID_NS',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    legalComments: 'none',
    write: false,
    logLevel: 'warning'
  })

  mermaidBundle = result.outputFiles[0].text
  writeFileSync(
    vendorPath,
    `/* mermaid ${mermaidVersion} — MIT — IIFE bundle generated by scripts/build.mjs; do not edit. */\n${mermaidBundle}\n`
  )
} else if (existsSync(vendorPath)) {
  // Plugin-only change on a machine without mermaid/esbuild: reuse the vendored bundle as it is.
  // Only vendor/mermaid.iife.js is read, never rewritten, so the result is byte-identical for an
  // unchanged src/plugin.js.
  const vendored = readFileSync(vendorPath, 'utf8')
  const header = /^\/\* mermaid (\S+) —/.exec(vendored)
  if (!header) {
    console.error('[build] vendor/mermaid.iife.js has no version header: cannot reuse it.')
    process.exit(1)
  }
  mermaidVersion = header[1]
  mermaidBundle = vendored.slice(vendored.indexOf('\n') + 1, -1)
  console.log(`[build] mermaid/esbuild not found: reusing the vendored bundle (mermaid ${mermaidVersion})`)
} else {
  console.error('[build] mermaid or esbuild not found, and no vendored bundle. Install them or point DSH_MERMAID_DEPS at a folder that has them.')
  process.exit(1)
}

const pluginBody = readFileSync(join(root, 'src', 'plugin.js'), 'utf8')

const assembled = `// @local/dsh-mermaid — client bundle GENERATED by scripts/build.mjs (do not edit).
// mermaid ${mermaidVersion} (MIT) — see vendor/NOTICES.md.
window.__ModuleLoader__.load({
  id: '@local/dsh-mermaid',
  factory: () => {
    var module = { exports: {} }
    var exports = module.exports
    try {
${indent(mermaidBundle, '      ')}
      var mermaid = (typeof __DSH_MERMAID_NS !== 'undefined' && __DSH_MERMAID_NS && (__DSH_MERMAID_NS.default || __DSH_MERMAID_NS)) || null
      if (!mermaid || typeof mermaid.render !== 'function') {
        throw new Error('[dsh-mermaid] the mermaid API is missing from the vendored bundle')
      }
      var plugin = (function (mermaid) {
${indent(pluginBody, '        ')}
      })(mermaid)
      exports.name = plugin.name
      exports.inject = plugin.inject
      exports.apply = plugin.apply
    } catch (error) {
      // An exception here would break the WHOLE entry (« Failed to load plugins »)
      // and leave the GUI unusable: we degrade instead, plugin disabled.
      console.error('[dsh-mermaid] cannot evaluate the bundle — plugin disabled', error)
    }
    return module.exports
  }
})
`

function indent(text, prefix) {
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join('\n')
}

mkdirSync(join(root, 'client'), { recursive: true })
const outPath = join(root, 'client', 'client.js')
writeFileSync(outPath, assembled)

// Immediate syntax check: a broken bundle must never be installed.
execFileSync(process.execPath, ['--check', outPath], { stdio: 'inherit' })

const size = (readFileSync(outPath).length / 1048576).toFixed(2)
console.log(`[build] mermaid ${mermaidVersion} (vendor/mermaid.iife.js)`)
console.log(`[build] client/client.js — ${size} MB, syntax OK`)
if (!existsSync(join(root, 'client', 'client.js'))) process.exit(1)