// scripts/build.mjs — produces `client/client.js` from `src/plugin.js`.
//
// The DSH module loader expects a bundle that calls
// `window.__ModuleLoader__.load({ id, factory })`. Here the factory receives the
// loader's `require` (React is in the platform's module table) and returns the
// plugin object { name, inject, apply }.
//
// The media player embeds NO library: the native <audio>/<video> are enough.
// The bundle is therefore tiny and is built without any external dependency.
//
// Usage: node scripts/build.mjs
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const PACKAGE_ID = '@local/dsh-media-player'

const body = readFileSync(join(root, 'src', 'plugin.js'), 'utf8')

const assembled = `// @local/dsh-media-player — client bundle GENERATED by scripts/build.mjs (do not edit).
// Source: src/plugin.js. No third-party code: the browser's native player.
window.__ModuleLoader__.load({
  id: '${PACKAGE_ID}',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    try {
      var React = require('react')
      var plugin = (function (React) {
${indent(body, '        ')}
      })(React)
      exports.name = plugin.name
      exports.inject = plugin.inject
      exports.apply = plugin.apply
      exports.__test = plugin.__test
    } catch (error) {
      // An exception here would break the WHOLE entry (« Failed to load plugins »)
      // and leave the GUI unusable: we degrade, plugin disabled.
      console.error('[dsh-media-player] cannot evaluate — plugin disabled', error)
    }
    return module.exports
  }
})
`

/** Indents a block of source to insert it in the factory. */
function indent(text, prefix) {
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join('\n')
}

mkdirSync(join(root, 'client'), { recursive: true })
const outPath = join(root, 'client', 'client.js')
writeFileSync(outPath, assembled)

// Immediate syntax check: a broken bundle must never be installed.
execFileSync(process.execPath, ['--check', outPath], { stdio: 'inherit' })

const bytes = readFileSync(outPath).length
console.log(`[build] client/client.js — ${bytes} bytes, syntax OK`)
