// scripts/build.mjs — produces `client/client.js`.
//
//   1. vendors `echarts` (official UMD, vendored to stay offline)
//      → injected into the factory with `module/exports/define` hidden so that
//        the UMD takes its global branch (otherwise it would attach itself to
//        the factory's `exports` and `window.echarts` would stay empty).
//   2. concatenates the DSH module-loader header + the vendor + the plugin
//      factory (src/plugin.js).
//
// Usage: node scripts/build.mjs
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pluginBody = readFileSync(join(root, 'src', 'plugin.js'), 'utf8')
const echartsUmd = readFileSync(join(root, 'vendor', 'echarts.min.js'), 'utf8')

const assembled = `// @local/dsh-db-viewer — client bundle GENERATED by scripts/build.mjs (do not edit).
// Readable source: src/plugin.js. Vendored ECharts: vendor/echarts.min.js (Apache-2.0).
window.__ModuleLoader__.load({
  id: '@local/dsh-db-viewer',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    try {
      var React = require('react')
      // The UMD vendor: module/exports/define passed as undefined to force the
      // global branch → window.echarts. Isolated failure: the Charts view
      // degrades, the rest of the plugin lives.
      var echarts = null
      try {
        ;(function (module, exports, define) {
${indent(echartsUmd, '          ')}
        }).call(typeof window !== 'undefined' ? window : globalThis, undefined, undefined, undefined)
        echarts = (typeof window !== 'undefined' && window.echarts) || (typeof globalThis !== 'undefined' && globalThis.echarts) || null
      } catch (error) {
        console.error('[dsh-db-viewer] echarts vendor unavailable — Charts view disabled', error)
      }
      var plugin = (function (React, echarts) {
${indent(pluginBody, '        ')}
      })(React, echarts)
      exports.name = plugin.name
      exports.inject = plugin.inject
      exports.apply = plugin.apply
      exports.__test = plugin.__test
    } catch (error) {
      // An exception here would break the WHOLE entry (« Failed to load plugins »)
      // and leave the GUI unusable: we degrade instead, plugin disabled.
      console.error('[dsh-db-viewer] cannot evaluate the bundle — plugin disabled', error)
    }
    return module.exports
  }
})
`

/** Indents a block of source so it can be inserted into the factory. */
function indent(text, prefix) {
  return text
    .split('\n')
    .map((line) => (line.length > 0 ? prefix + line : line))
    .join('\n')
}

mkdirSync(join(root, 'client'), { recursive: true })
const outPath = join(root, 'client', 'client.js')
writeFileSync(outPath, assembled)

// Immediate syntax check — `node --check` is a false green on Node 26
// (measured): we really parse through a compiled Function.
execFileSync(process.execPath, ['-e', 'new Function(require("fs").readFileSync(process.argv[1], "utf8"))', outPath], { stdio: 'inherit' })

const ko = (readFileSync(outPath).length / 1024).toFixed(0)
console.log(`[build] client/client.js — ${ko} KB, real parse OK`)
