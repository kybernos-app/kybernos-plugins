let lang = 'en'
/** `fr` or `en`; anything else is English. */
export const setLang = (l) => { lang = String(l || '').slice(0, 2).toLowerCase() === 'fr' ? 'fr' : 'en' }
export const getLang = () => lang
export const T = (en) => (lang === 'fr' && Object.prototype.hasOwnProperty.call(FR, en) ? FR[en] : en)
/** The language of a standalone file: the page's own `lang`, else the browser's. */
export const detectLang = () => {
  try { return (document.documentElement.lang || navigator.language || 'en').slice(0, 2).toLowerCase() === 'fr' ? 'fr' : 'en' } catch (e) { return 'en' }
}
